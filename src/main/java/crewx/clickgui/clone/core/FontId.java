package crewx.clickgui.clone.core;

/** Fontes lógicas usadas pela GUI. Cada backend decide como desenhá-las. */
public enum FontId {
    /** Nome dos módulos. */
    MODULE,
    /** Título do painel (categoria). */
    HEADER,
    /** Labels e valores dos sliders/settings. */
    LABEL,
    /** Textos pequenos (dicas no canto da tela). */
    SMALL,
    /** Fonte de ícones das categorias. */
    ICON
}
